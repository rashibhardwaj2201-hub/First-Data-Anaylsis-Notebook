import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

print("Libraries imported successfully!")

import pandas as pd

df = pd.read_csv('/content/sales.csv')

print("Dataset loaded successfully!")
print("\nDataset:")
display(df)

print("\nDataset Shape:", df.shape)

# First 5 rows
print("First 5 Records:")
display(df.head())

# Dataset information
print("Dataset Information:")
df.info()

# Statistical summary
print("Statistical Summary:")
display(df.describe())

# Check missing values
print("Missing Values:")
display(df.isnull().sum())

# Check duplicate records
print("Duplicate Records:", df.duplicated().sum())

# Remove duplicate records
df = df.drop_duplicates()

# Check data types
print("\nData Types:")
print(df.dtypes)

print("\nData Cleaning Completed!")

# Overall Sales
print("Total Revenue:", df['TotalSales'].sum())

# Category-wise Sales
print("\nCategory-wise Sales:")
display(df.groupby('Category')['TotalSales'].sum())

# Total Quantity Sold
print("\nTotal Quantity Sold:", df['Quantity'].sum())

# Average Order Value
print("\nAverage Order Value:", df['TotalSales'].mean())

# Highest Sales
print("\nHighest Sale:", df['TotalSales'].max())

import matplotlib.pyplot as plt

category_sales = df.groupby('Category')['TotalSales'].sum()

plt.figure(figsize=(8,5))
category_sales.plot(kind='bar')

plt.title('Category-wise Sales Analysis')
plt.xlabel('Category')
plt.ylabel('Total Sales')
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

df['Date'] = pd.to_datetime(df['Date'])

daily_sales = df.groupby('Date')['TotalSales'].sum()

plt.figure(figsize=(9,5))
daily_sales.plot(kind='line', marker='o')

plt.title('Daily Sales Trend')
plt.xlabel('Date')
plt.ylabel('Total Sales')
plt.grid(True)
plt.tight_layout()
plt.show()

quantity_sales = df.groupby('Category')['Quantity'].sum()

plt.figure(figsize=(7,5))
quantity_sales.plot(kind='pie', autopct='%1.1f%%')

plt.title('Quantity Sold by Category')
plt.ylabel('')
plt.show()

print("========== BUSINESS INSIGHTS ==========")

print("1. Total Revenue:", df['TotalSales'].sum())

print("2. Best Performing Category:",
      df.groupby('Category')['TotalSales'].sum().idxmax())

print("3. Lowest Performing Category:",
      df.groupby('Category')['TotalSales'].sum().idxmin())

print("4. Total Orders:", df['OrderID'].nunique())

print("5. Total Quantity Sold:", df['Quantity'].sum())

print("6. Average Sales:", round(df['TotalSales'].mean(), 2))

print("========== ANALYSIS COMPLETED ==========")

